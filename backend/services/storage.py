"""Files that belong to a document: the original PDF and its figure images.

Layout:  data/documents/<document_id>/original.pdf
         data/documents/<document_id>/figures/fig_001.png
"""
from __future__ import annotations

import shutil
import uuid
from pathlib import Path

from config import settings


class DocumentStorage:
    def __init__(self, root: str | Path | None = None):
        self.root = Path(root or settings.data_dir) / "documents"
        self.root.mkdir(parents=True, exist_ok=True)

    def _dir(self, document_id: str, create: bool = False) -> Path:
        """Folder of one document.

        Document ids are uuid4 strings generated by the app; anything else raises
        ValueError, so an id can never point outside the storage folder.
        """
        uuid.UUID(document_id)
        path = self.root / document_id
        if create:
            path.mkdir(parents=True, exist_ok=True)
        return path

    def save_pdf(self, document_id: str, data: bytes) -> Path:
        path = self._dir(document_id, create=True) / "original.pdf"
        path.write_bytes(data)
        return path

    def pdf_path(self, document_id: str) -> Path:
        return self._dir(document_id) / "original.pdf"

    def figure_path(self, document_id: str, index: int, create: bool = False) -> Path:
        folder = self._dir(document_id, create=create) / "figures"
        if create:
            folder.mkdir(parents=True, exist_ok=True)
        return folder / f"fig_{index:03d}.png"

    def save_figure(self, document_id: str, index: int, image) -> Path:
        path = self.figure_path(document_id, index, create=True)
        image.save(path, format="PNG")
        return path

    def delete(self, document_id: str) -> None:
        shutil.rmtree(self._dir(document_id), ignore_errors=True)
